create or replace function public.telechat_guard_group_member_v32()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  active_count integer;
begin
  if not exists (
    select 1 from public.telechat_group_calls
    where id=new.call_id and status='active'
  ) then
    raise exception 'Звонок уже завершён';
  end if;

  if new.status in ('invited','joined')
     and (tg_op='INSERT' or old.status not in ('invited','joined')) then
    select count(*) into active_count
    from public.telechat_group_call_members
    where call_id=new.call_id
      and status in ('invited','joined')
      and lower(nick)<>lower(new.nick);
    if active_count >= 6 then
      raise exception 'В звонке может быть не больше 6 участников';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists telechat_guard_group_member_v32 on public.telechat_group_call_members;
create trigger telechat_guard_group_member_v32
before insert or update on public.telechat_group_call_members
for each row execute function public.telechat_guard_group_member_v32();

create or replace function public.telechat_guard_group_signal_v32()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1 from public.telechat_group_calls
    where id=new.call_id and status='active'
  ) then
    raise exception 'Звонок уже завершён';
  end if;
  if not exists (
    select 1 from public.telechat_group_call_members
    where call_id=new.call_id and lower(nick)=lower(new.from_nick) and status='joined'
  ) then
    raise exception 'Отправитель не участвует в звонке';
  end if;
  if not exists (
    select 1 from public.telechat_group_call_members
    where call_id=new.call_id and lower(nick)=lower(new.to_nick) and status in ('invited','joined')
  ) then
    raise exception 'Получатель не участвует в звонке';
  end if;
  return new;
end;
$$;

drop trigger if exists telechat_guard_group_signal_v32 on public.telechat_group_call_signals;
create trigger telechat_guard_group_signal_v32
before insert on public.telechat_group_call_signals
for each row execute function public.telechat_guard_group_signal_v32();

