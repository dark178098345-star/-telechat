create extension if not exists pgcrypto;

create table if not exists public.telechat_group_calls (
  id uuid primary key default gen_random_uuid(),
  host_nick text not null references public.users(nick) on update cascade on delete cascade,
  origin_peer_nick text not null references public.users(nick) on update cascade on delete cascade,
  status text not null default 'active' check (status in ('active','ended','cancelled')),
  created_at bigint not null default ((extract(epoch from clock_timestamp()) * 1000)::bigint),
  started_at bigint,
  ended_at bigint
);

create table if not exists public.telechat_group_call_members (
  call_id uuid not null references public.telechat_group_calls(id) on delete cascade,
  nick text not null references public.users(nick) on update cascade on delete cascade,
  invited_by text not null references public.users(nick) on update cascade on delete cascade,
  status text not null default 'invited' check (status in ('invited','joined','rejected','left','missed')),
  invited_at bigint not null default ((extract(epoch from clock_timestamp()) * 1000)::bigint),
  joined_at bigint,
  left_at bigint,
  primary key (call_id,nick)
);

create table if not exists public.telechat_group_call_signals (
  id bigint generated by default as identity primary key,
  call_id uuid not null references public.telechat_group_calls(id) on delete cascade,
  from_nick text not null references public.users(nick) on update cascade on delete cascade,
  to_nick text not null references public.users(nick) on update cascade on delete cascade,
  kind text not null check (kind in ('offer','answer','candidate')),
  payload jsonb not null,
  created_at bigint not null default ((extract(epoch from clock_timestamp()) * 1000)::bigint),
  constraint telechat_group_signal_different_users check (lower(from_nick) <> lower(to_nick))
);

create index if not exists telechat_group_calls_status_idx
  on public.telechat_group_calls(status,created_at desc);
create index if not exists telechat_group_members_nick_idx
  on public.telechat_group_call_members(nick,status,invited_at desc);
create index if not exists telechat_group_members_call_idx
  on public.telechat_group_call_members(call_id,status);
create index if not exists telechat_group_signals_target_idx
  on public.telechat_group_call_signals(call_id,to_nick,id);

